#[cfg(test)]
mod tests {
    use super::*;

    /// 漂移锁：条数与关键成员固定；顺序敏感的两处（长词先于子串）单独钉住。
    #[test]
    fn word_lists_are_stable() {
        assert_eq!(SENSITIVE_COLS.len(), 9);
        assert_eq!(TIME_TOKENS.len(), 12);
        assert_eq!(FOLLOWUP_MARKS.len(), 22);
        assert_eq!(STRIP_WORDS.len(), 88); // 计数漂移锁：加词同改
    }

    /// 🔴 新加的两个时间词也必须遵守「长词先于子串」：
    /// 「上半年」排在单字「年」之后的话，剥完「年」会留下「上半」，
    /// 于是残留守卫把「2026年上半年…」判成有实义残留、整条回落 LLM。
    #[test]
    fn half_year_words_precede_single_year() {
        let pos = |w: &str| STRIP_WORDS.iter().position(|x| *x == w).unwrap();
        assert!(pos("上半年") < pos("年"), "「上半年」必须先于单字「年」被剥");
        assert!(pos("下半年") < pos("年"), "「下半年」必须先于单字「年」被剥");
        // 「是哪些」必须先于「哪些」（否则剥完「哪些」留下孤零零的「是」，而「是」不在表里）
        assert!(pos("是哪些") < pos("哪些"), "「是哪些」必须先于「哪些」");
        // 「我们」先于单字「我」（否则剥完「我」留下「们」，而「们」不在表里）
        assert!(pos("我们") < pos("我"), "「我们」必须先于单字「我」被剥");
        assert!(pos("一共花了多少钱") < pos("花了多少钱"), "完整费用问法必须先剥");
        assert!(pos("一共花了多少钱") < pos("一共"), "长费用问法必须先于「一共」");
        assert!(pos("花了多少钱") < pos("多少"), "费用问法必须先于通用「多少」");
    }

    /// 🔴 **「还/剩」绝不许进虚词表**。
    ///
    /// 「**还**有多少余额 / **还剩**多少」隐含 `balance > 0`（余额为 0 的不算「还有」，
    /// 实测 28 vs 23），而装配器表达不了这个条件。把它们剥掉 = 残留守卫放行 =
    /// 装配出一条不带 `> 0` 的 SQL、**确定性地多 5 行**。
    /// 这条断言就是那道闸：谁想「顺手把这两个虚词也加上」，先读这里。
    #[test]
    fn residual_semantics_words_must_not_be_stripped() {
        for w in ["还", "剩", "还有", "还剩"] {
            assert!(!STRIP_WORDS.contains(&w), "「{w}」承载 > 0 的语义，装配器兑现不了，不许剥");
        }
    }

    /// 🔴 新加的排序/疑问词**不许吃掉实体名里的字**。
    /// 这些词是通用虚词，但表是全仓共用的 —— 加错一个就会让残留守卫放过一个值过滤，
    /// 而那正是 E16 那条实测翻车（"线下"被静默丢弃）的形态。
    #[test]
    fn new_strip_words_are_generic_not_entity_tokens() {
        for w in ["是哪些", "哪些", "最高", "最多", "最少", "最大", "最小", "箱", "上半年", "下半年",
                  "一共花了多少钱", "花了多少钱", "一共", "总共"] {
            assert!(STRIP_WORDS.contains(&w), "{w} 不在表里");
            // 全是 ≥1 字的通用词，且**不含**会构成商品/客户名的实义词根。
            // 弱判据（承认）：「不含元/件/装」不会拦住下一个新实义字根 —— 它只是防呆最低线，
            // 真判据是上面注释里的实体名风险分析，加词时照着写一遍。
            assert!(!w.contains('元') && !w.contains('件') && !w.contains('装'), "{w} 有实体名风险");
        }
    }

    #[test]
    fn strip_words_long_before_substring() {
        let pos = |w: &str| STRIP_WORDS.iter().position(|x| *x == w).unwrap();
        // 「上月/上个月」的先后其实不改变剥词结果（「上个月」剥完「上月」剩的「个」由量词行兜住）；
        // 钉住顺序是防御性冗余——真把「上个月」挪前面，结果不变、这句断言会先红，提醒你多看一眼。
        assert!(pos("上月") < pos("上个月"), "「上月」必须先于「上个月」被剥");
        assert!(pos("是多少") < pos("多少"), "「是多少」必须先于「多少」被剥");
        assert!(pos("今天") < pos("天"), "「今天」必须先于单字「天」被剥");
        // 🔴 这两对是**实测踩出来的**，不是补齐式的洁癖：
        // 词序反了不会报错，只会让一族问句静默回落 LLM（剥完剩一个孤零零的「最」/「本」）。
        assert!(pos("最近") < pos("近"), "「最近」必须先于单字「近」——否则剥完剩一个「最」");
        for q in ["本季度", "上季度", "这季度"] {
            assert!(pos(q) < pos("季度"), "「{q}」必须先于「季度」——否则剥完剩一个「本/上/这」");
        }
        // 反面（防恒真）：上面那些词真的都在表里，否则 `pos()` 会 panic 而不是断言失败 ——
        // 这一行让「词被删掉」时的报错说人话
        for w in ["最近", "近", "本季度", "季度"] {
            assert!(STRIP_WORDS.contains(&w), "{w} 不在表里了");
        }
    }

    /// 🔴 词序修好之后，这两族剥完必须**真的为空**（上面那条只判下标，不判结果）。
    /// 判据形态是「模拟剥词」而不是调 `has_residue` —— 后者还叠了 CJK 判定，
    /// 混在一起时看不出到底是词表的问题还是判定的问题。
    #[test]
    fn the_two_fixed_families_strip_clean() {
        let strip = |q: &str| {
            let mut s = q.to_string();
            for w in STRIP_WORDS {
                s = s.replace(w, "");
            }
            s
        };
        // 改前实测：「最近三个月的销量」→ `最`；「本季度的销量」→ `本`
        for q in ["最近三个月的销量", "近三个月的销量", "本季度的销量", "上季度的销量"] {
            assert_eq!(strip(q), "销量", "{q} 剥完不干净");
        }
        for (q, expected) in [
            ("活动临促人员费用一共花了多少钱", "活动临促人员费用"),
            ("活动执行人员费用花了多少钱", "活动执行人员费用"),
            ("活动费用一共多少", "活动费用"),
            ("活动费用总共多少", "活动费用"),
        ] {
            assert_eq!(strip(q), expected, "{q} 的聚合语气未剥干净");
        }
    }
}
