//! 通用中文虚词与词表的**单一事实源**。全部 `pub const`，零算法。
//!
//! 收纳边界（`nl/mod.rs` 的收纳判据）：只收无业务语义的词——虚词、时间词、排序词、
//! 列名黑名单。业务名词（指标名/维度名/同义词）一律留注册表，由 server 侧参数传入。

/// 剥词残留守卫用的通用虚词/时间词/排序词表（`nl::text::has_residue_with` 的默认词表）。
/// **顺序即行为**（§0 D9）：长词必须先于其子串（「上月」先于「上个月」、「是多少」先于「多少」），
/// 重排会让子串先被剥掉、长词再也匹配不上，残留判定随之变化。
/// 搬运源 `server/src/direct.rs:441-447`。
pub const STRIP_WORDS: &[&str] = &[
    "今天", "今日", "昨天", "昨日", "本月", "这个月", "上月", "上个月", "本周", "这周", "今年",
    // 「上半年/下半年」必须排在单字「年」之前（长词先剥，`strip_words_long_before_substring` 守着）。
    // 它们是无歧义的时间词，不可能是实体名 —— 而少了它们，「上半年」剥完「年」会留下「上半」，
    // 于是「2026年上半年每个月的销量」被残留守卫判成有实义残留、整条回落 LLM。
    "上半年", "下半年",
    // 🔴 「最近」必须排在单字「近」**之前**（长词先剥）。原来是 `"近", "最近"`，
    // 于是剥完「近」留下孤零零的「最」（不在表里）→ 「**最近**三个月的销量」被残留守卫
    // 判成有实义残留、整条回落 LLM，而「近三个月的销量」好的。
    // 实测：`pos(近)=15 / pos(最近)=16`，「最近三个月销售额是多少」剥完 = `最`。
    // 影响面是**全仓**残留守卫（装配器 + `agg_template` 吃同一张表），不是某一条路径。
    "最近", "近",
    // 「本/上/这季度」必须排在「季度」之前，同一个道理：只有「季度」时剥完剩一个「本」。
    // 三个都是 `time_predicate::rule_quarter` 认得的（`head.contains('本'|'这'|'上')`），
    // 剥了不会出现「剥得掉但解析不了」那种更坏的情形。
    "本季度", "上季度", "这季度",
    // 「年初至今」必须排在单字「年」之前：`window_includes_today`（time.rs）认这个形态，
    // 剥完「年」留下「初至今」→ 再剥「至今」剩「初」→ 判残留回落。
    "年初至今",
    "上周", "去年", "天", "周", "月", "年", "季度", "至今",
    // 单位量词：「…的销量是多少**箱**」里的「箱」原本是实义残留，整条问句于是回落 LLM。
    // 只加**已被实测挡住过**的那个，不预先铺一张单位表 —— 单位词判宽了会吃掉实体名里的字
    //（`元`：元气森林；`件`：件套）。「箱」作为纯量词无此风险：真正的值过滤如「整箱订单」
    // 剥掉「箱」后仍留「整」，照旧被守卫拦下。
    "箱",
    // 「我们」必须排在单字「我」之前（长词先剥）：否则剥完「我」留下孤零零的「们」，
    // 而「们」不在表里 → 残留守卫把「**我们**送出去的赠品有多少箱」判成有实义残留、整条回落 LLM。
    // 纯代词，无实体名风险（与既有的「我」「帮我」同类）。
    // 费用问法只承载聚合语气，不改变指标口径。最长短语必须排在各自子串之前。
    "一共花了多少钱", "花了多少钱", "一共", "总共",
    "按", "各", "的", "是多少", "多少", "有", "查询", "查", "统计", "看看", "帮我", "我们", "我", "一下",
    "排行", "排名", "前", "第", "名", "top", "TOP", "Top", "对比", "和", "与", "分别",
    // 最高/最多/最少 与「哪些/是哪些」：与「排行/排名」同类的**排序词与疑问词**。
    // 少了它们，「2026年6月销量最高的5个商品分类**是哪些**」剥完仍留「最高」「哪些」
    // → 残留守卫拦 → 一道指标与维度都命中、gold 分组表达式与维度声明逐字相同的题
    // 只能回落 LLM（实测它在那条路上稳定给 +30.5% 的错值）。
    // 「最高」必须先于「最」类单字不存在的问题：表里没有单字「最」，无需排序约束。
    // 「最好」同族：detect_top_n 认「最好」（time.rs 最高级分支），守卫侧也得剥，
    // 否则「卖得最好的10个商品」TopN 认得出、残留守卫却把「最好」留下判回落。
    "是哪些", "哪些", "哪个", "最高", "最多", "最少", "最大", "最小", "最好",
    // 「目前/现在/当前」：与「今天/本月」同类的时间副词，装配器本来就按最新/全量取数。
    // 「是谁/谁」：疑问词。两组都无实体名风险。
    //
    // 🔴 **刻意不加「还/剩」**：「**还**有多少余额 / **还剩**多少」隐含 `> 0`
    //（余额为 0 的不算「还有」，见 `meta.pitfall` 里 t_customer_balance 那条，实测 28 vs 23），
    // 而装配器**表达不了**这个条件。剥掉它 = 装配出一条不带 `> 0` 的 SQL、
    // 确定性地多 5 行 —— 那是把「守卫拦得对」换成「确定地答错」。
    // 同 GOODS17/TopN 那次的教训：只剥装配器**能兑现**的词。
    "目前", "现在", "当前", "是谁", "谁",
    // 纯量词「个/名/条/项」：`…最高的5**个**商品分类` 剥掉数字后剩下的就是它。
    // ⚠️ 顺序纪律：这一行必须在 `detect_top_n` **已经认得「最高的N个」之后**才敢加 ——
    // 否则解锁的题会按默认 200 行出数、行数不符，把「飘着的失败」变成「确定的失败」。
    "个", "名", "条", "项",
    "一", "二", "两", "三", "四", "五", "六", "七", "八", "九", "十", "百",
];

